#!/usr/bin/env python3
"""gen_f08_wrappers.py — the Fortran 2008 (`use mpi_f08`) wrappers, generated
from the `use mpi` / mpif.h wrappers.

    gen_f08_wrappers.py SOURCE.c OUTPUT.inc     (make gen-f08)

A program built with `use mpi_f08` calls the library's f08 entry points,
not the mpif.h ones: `mpi_send_f08_` (Open MPI, and MPICH for routines
without a buffer) or `mpi_send_f08ts_` (MPICH, routines with a choice
buffer, passed as a descriptor). Their arguments are what the mpif.h
binding takes, by reference, with two differences that the wrappers never
look inside: handles are TYPE(MPI_Comm) etc. (a struct holding the same
INTEGER, so MPI_Comm_f2c(*comm) still works) and buffers may be
descriptors. `ierror` is OPTIONAL, so it may be NULL.

For every `void mpi_X_(...)` wrapper in SOURCE this writes
`mpi_X_f08_` and `mpi_X_f08ts_` with the same parameters and body, except
that the call to the library's `pmpi_X_` becomes a call to the library's
own `mpi_X_f08_` / `mpi_X_f08ts_`, found with dlsym(RTLD_NEXT) on first
use. That avoids the profiling-name schemes, which differ between MPI
libraries (Open MPI pmpi_X_f08_, MPICH pmpir_X_f08ts_), and the
tool-depth guard stops a library whose f08 binding calls the C binding
from being counted twice. The output is committed; `make check` fails if
it is stale (test-f08-generated)."""
import re, sys

HEADER = """/* GENERATED by tools/gen_f08_wrappers.py from {src} — do not edit.
 * The `use mpi_f08` wrappers: see the generator for how and why. */
"""

# body: one line "{ ...; }" or "{" ... "}" each on a line of its own
DEF = re.compile(r"^void (mpi_[a-z0-9_]+?)_\((.*?)\)\s*\n(\{[^\n]*\}$|\{\n.*?\n\})", re.S | re.M)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    text = open(src).read()
    found = DEF.findall(text)
    if not found:
        sys.exit(f"gen_f08_wrappers: no Fortran wrappers found in {src}")
    parts = [HEADER.format(src=src)]
    for name, params, body in found:
        if f"pmpi_{name[4:]}_(" not in body:
            sys.exit(f"gen_f08_wrappers: {name}_ does not call pmpi_{name[4:]}_: cannot generate")
        for suffix in ("f08_", "f08ts_"):
            sym = f"{name}_{suffix}"
            new = body.replace(f"pmpi_{name[4:]}_(", f"F08_REAL({sym})(")
            parts.append(f"static void *f08_real_{sym};\n"
                         f"void {sym}({params})\n{new}\n")
    open(out, "w").write("\n".join(parts))
    print(f"gen_f08_wrappers: {len(found)} wrappers x 2 names -> {out}")


main()
